  static String lookup(
    String languageCode,
    String key, {
    Map<String, String> params = const {},
  }) {
    final map = switch (languageCode) {
      'en' => en,
      'pt' => pt,
      _ => es,
    };
    var text = map[key] ?? es[key] ?? key;
    for (final e in params.entries) {
      text = text.replaceAll('{${e.key}}', e.value);
    }
    return text;
  }

